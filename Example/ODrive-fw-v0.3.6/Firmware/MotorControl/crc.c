/**
 * @brief CRC16-CCITT校验计算函数
 *
 * 使用查表法逐字节计算CRC16校验值。
 *
 * 【计算过程】
 * 对于输入数据缓冲区中的每个字节，执行以下步骤:
 * 1. 将当前CRC值的高8位(cksum >> 8)与输入字节进行异或
 * 2. 取结果的低8位作为查表索引(& 0xFF)
 * 3. 从crc16_tab表中取出对应的预计算CRC值
 * 4. 将当前CRC值左移8位(cksum << 8)，保留低8位的影响
 * 5. 将查表结果与移位后的CRC值进行异或，得到新的CRC值
 *
 * 【公式】
 *   new_crc = crc_table[((old_crc >> 8) ^ data_byte) & 0xFF] ^ (old_crc << 8)
 *
 * 【示例】(假设输入数据为 "AB" = {0x41, 0x42})
 *   初始: cksum = 0x0000
 *   第1字节(0x41):
 *     index = ((0x0000 >> 8) ^ 0x41) & 0xFF = 0x41
 *     cksum = crc16_tab[0x41] ^ (0x0000 << 8) = crc16_tab[0x41] ^ 0x0000
 *           = 0x4235 ^ 0x0000 = 0x4235
 *   第2字节(0x42):
 *     index = ((0x4235 >> 8) ^ 0x42) & 0xFF = (0x42 ^ 0x42) & 0xFF = 0x00
 *     cksum = crc16_tab[0x00] ^ (0x4235 << 8) = 0x0000 ^ 0x3500 = 0x3500
 *   返回: 0x3500
 *
 * @param buf 指向待校验数据缓冲区的指针
 * @param len 数据长度(字节数)
 * @return 16位CRC校验值
 */
unsigned short crc16(unsigned char *buf, unsigned int len) {
    unsigned int i;              // 循环计数器
    unsigned short cksum = 0;    // CRC校验和，初始值为0

    // 逐字节处理数据缓冲区
    for (i = 0; i < len; i++) {
        /*
         * 查表法核心计算:
         *   (((cksum >> 8) ^ *buf++) & 0xFF)
         *     - cksum >> 8: 取出CRC值的高8位
         *     - ^ *buf++:   与当前输入字节异或，同时指针后移
         *     - & 0xFF:     确保索引在0-255范围内
         *   crc16_tab[...]: 用索引查表获取预计算的CRC贡献值
         *   ^(cksum << 8):  将原CRC值左移8位后与查表结果异或
         */
        cksum = crc16_tab[(((cksum >> 8) ^ *buf++) & 0xFF)] ^(cksum << 8);
    }

    return cksum;  // 返回最终计算得到的CRC16校验值
}
