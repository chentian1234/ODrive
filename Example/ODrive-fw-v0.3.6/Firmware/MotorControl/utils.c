/**
 * @brief 正模运算（数学意义上的取模运算）
 *
 * @details
 * C语言中的%运算符实现的是"取余"（remainder）而非"取模"（modulo）。
 * 两者的区别在于商向哪个方向取整：
 * - 取余：商向零取整（truncation），余数符号与被除数相同
 * - 取模：商向负无穷取整（floor），余数符号与除数相同
 *
 * 示例：
 *   -1 % 5   = -1   （C语言取余）
 *   mod(-1, 5) = 4  （数学取模，因为 -1 = (-1)×5 + 4）
 *
 * 在电机控制中，编码器计数、电角度计算等场景需要数学意义上的取模运算，
 * 因此实现此函数。
 *
 * 实现方法：
 * 先计算C语言取余 r = dividend % divisor，
 * 如果 r < 0，则 r += divisor，使结果始终为正。
 *
 * @param[in] dividend 被除数（可以为正或负）
 * @param[in] divisor  除数（应不为0）
 * @return 正模运算结果，范围 [0, |divisor|)
 *
 * @note 参考: https://stackoverflow.com/a/19288271
 */
// 取模运算（区别于取余），详见 https://stackoverflow.com/a/19288271
int mod(int dividend, int divisor) {
    // 先使用C语言的取余运算符
    int r = dividend % divisor;
    // 如果余数为负，加上除数使其变为正数（数学意义上的模）
    return (r < 0) ? (r + divisor) : r;
}

