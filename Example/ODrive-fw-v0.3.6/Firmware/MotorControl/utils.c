/*                         高精度时间戳函数实现                                  */
/* ========================================================================== */

/**
 * @brief 获取系统启动以来的微秒数（高精度时间戳）
 *
 * @details
 * 提供一个精度为微秒级的时间戳，适用于需要高精度定时的场景，
 * 如测量脉冲宽度、计算通信时序等。
 *
 * 实现原理：
 * 结合两个时间源来获取高精度的时间戳：
 * 1. HAL_GetTick()：RTOS的毫秒级系统滴答，提供"大尺度"时间基准
 * 2. TIM_TIME_BASE->CNT：一个运行在1MHz频率下的定时器计数器，
 *    提供毫秒内的微秒级偏移量
 *
 * 最终结果 = 毫秒数 × 1000 + 定时器计数值（微秒）
 *
 * 竞争条件处理：
 * 由于毫秒进位和定时器计数器读取不是原子操作，
 * 如果在读取毫秒值和计数器值之间发生了毫秒进位，
 * 会导致结果不准确。使用do-while循环检测并避免这种情况：
 * 先读取毫秒值，再读取计数器值，
 * 如果再次读取毫秒值发生了变化，说明发生了进位，需要重新读取。
 *
 * @return 系统启动以来的微秒数（32位无符号整数）
 * @note 32位微秒计数器约在71.5分钟后溢出回绕。
 *       如果需要更长时间跨度的高精度计时，需要额外处理溢出。
 */
// @brief: 返回系统启动以来的微秒数
uint32_t micros(void) {
    register uint32_t ms, cycle_cnt;
    do {
        ms = HAL_GetTick();           // 先读取毫秒级系统滴答
        cycle_cnt = TIM_TIME_BASE->CNT; // 再读取定时器计数器（微秒偏移）
    } while (ms != HAL_GetTick());    // 如果在此期间毫秒值发生变化，重新读取

    // 合并毫秒和微秒：毫秒×1000 + 定时器计数值
    // 假设TIM_TIME_BASE配置为1MHz计数频率，每个计数 = 1微秒
    return (ms * 1000) + cycle_cnt;
}

