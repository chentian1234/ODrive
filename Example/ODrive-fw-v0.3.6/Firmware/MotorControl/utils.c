/**
 * @brief 1/√3 的预计算值
 * @details √3 ≈ 1.73205080757，因此 1/√3 ≈ 0.57735026919
 *          该值在SVM算法中用于判断矢量所在的扇区：
 *          - tan(30°) = 1/√3，作为扇区边界的斜率
 *          - 用于将β分量转换为与α分量可比较的比例值
 *          预计算为常量避免在运行时进行浮点开方和除法运算，提高执行效率。
 */
static const float one_by_sqrt3 = 0.57735026919f;

/**
 * @brief 2/√3 的预计算值
 * @details √3 ≈ 1.73205080757，因此 2/√3 ≈ 1.15470053838
 *          该值在SVM算法中用于计算矢量作用时间：
 *          - 在伏秒平衡方程中，相邻矢量的作用时间计算需要乘以 2/√3
 *          - 这是SVM合成矢量的关键系数
 *          预计算为常量避免运行时除法运算。
 */
static const float two_by_sqrt3 = 1.15470053838f;

/* ========================================================================== */
/*                     空间矢量调制（SVM）函数实现                              */
/* ========================================================================== */

/**
 * @brief 空间矢量调制（SVM）算法完整实现
 *
 * @details
 * 空间矢量调制（Space Vector Modulation, SVM）是三相逆变器PWM调制的核心算法，
 * 广泛应用于电机FOC（磁场定向控制）系统中。
 *
 * ========================== 算法原理详解 ==========================
 *
 * 【1. 三相逆变器的开关状态】
 * 三相桥式逆变器有3个桥臂（A、B、C），每个桥臂有上下两个开关管。
 * 为避免直通短路，同一桥臂上下管不能同时导通。因此有2³=8种开关状态：
 * - 6个有效状态：V1(100)、V2(110)、V3(010)、V4(011)、V5(001)、V6(101)
 * - 2个零状态：  V0(000)、V7(111) —— 三相输出相同，线电压为零
 *
 * 【2. 空间电压矢量】
 * 将6个有效开关状态映射到α-β平面，得到6个空间电压矢量：
 * - 它们幅值相等（2/3·Vdc），方向互差60°，构成正六边形的6个顶点
 * - V1指向0°，V2指向60°，V3指向120°，依此类推
 * - 六边形被分为6个扇区（sextant），每个扇区60°
 *
 * 【3. 矢量合成原理】
 * 在任一扇区内，目标电压矢量可由相邻的两个有效矢量和零矢量合成：
 *   Vref = (T1/Ts)·V1 + (T2/Ts)·V2 + (T0/Ts)·V0
 * 其中T1、T2为有效矢量的作用时间，T0为零矢量作用时间，Ts为PWM周期。
 * 根据伏秒平衡：T1 + T2 + T0 = Ts
 *
 * 【4. 扇区判断】
 * 利用tan(30°) = 1/√3作为边界斜率，通过比较β/α与±1/√3的关系确定扇区：
 * - 第一象限(α≥0, β≥0)：若β/α > 1/√3 → 扇区2，否则 → 扇区1
 * - 第二象限(α<0, β≥0)： 若-β/α > 1/√3 → 扇区3，否则 → 扇区2
 * - 第四象限(α≥0, β<0)： 若-β/α > 1/√3 → 扇区5，否则 → 扇区6
 * - 第三象限(α<0, β<0)：  若β/α > 1/√3 → 扇区4，否则 → 扇区5
 *
 * 【5. PWM占空比计算】
 * 计算得到T1、T2后（归一化为Ts=1），采用七段式SVM对称分布：
 *   tA = (1 - T1 - T2) / 2    ← 零矢量均分
 *   tB = tA + T1
 *   tC = tB + T2
 * 各扇区的相位分配不同，需要根据扇区编号调整A/B/C三相的对应关系。
 *
 * 【6. 线性调制区限制】
 * SVM的线性调制区最大输出幅值为 Vdc/√3（相电压峰值），
 * 对应α-β平面上内切于六边形的圆，半径为√3/2 ≈ 0.866。
 * 超过此值进入过调制区，输出波形将产生失真。
 *
 * @param[in]  alpha α轴电压分量（Clarke变换结果，归一化值）
 * @param[in]  beta  β轴电压分量（Clarke变换结果，归一化值）
 * @param[out] tA    A相PWM占空比输出（0.0~1.0）
 * @param[out] tB    B相PWM占空比输出（0.0~1.0）
 * @param[out] tC    C相PWM占空比输出（0.0~1.0）
 * @return 状态码：0表示成功，-1表示输入超出线性调制区
 */
int SVM(float alpha, float beta, float* tA, float* tB, float* tC) {
    int Sextant;  // 扇区编号（1~6）

    /* ===== 扇区判断 =====
     * 根据α-β矢量的坐标位置，确定其所在的60°扇区。
     * 使用 1/√3 作为边界斜率进行判断。
     * 判断顺序：先判断β的正负确定上半平面/下半平面，
     *           再判断α的正负确定象限，
     *           最后用斜率阈值精确判定扇区。
     */
    if (beta >= 0.0f) {
        if (alpha >= 0.0f) {
            // 第一象限：α≥0, β≥0
            // 边界线斜率 = 1/√3 ≈ 0.577（即30°线）
            // β > α·tan(30°) → 在30°线上方 → 扇区2（30°~90°）
            // 否则 → 扇区1（0°~30°）
            if (one_by_sqrt3 * beta > alpha)
                Sextant = 2; // 扇区2：V2-V3边界区域（30°~90°）
            else
                Sextant = 1; // 扇区1：V1-V2边界区域（0°~30°）

        } else {
            // 第二象限：α<0, β≥0
            // 边界线斜率 = -1/√3（即150°线，在第二象限表现为-β/α = 1/√3）
            // -β > α·tan(30°) 等价于 β/(-α) > 1/√3
            if (-one_by_sqrt3 * beta > alpha)
                Sextant = 3; // 扇区3：V3-V4边界区域（90°~150°）
            else
                Sextant = 2; // 扇区2：V2-V3边界区域（30°~90°的延续）
        }
    } else {
        if (alpha >= 0.0f) {
            // 第四象限：α≥0, β<0
            // 边界线对应330°（即-30°）
            if (-one_by_sqrt3 * beta > alpha)
                Sextant = 5; // 扇区5：V5-V6边界区域（210°~270°的对应）
            else
                Sextant = 6; // 扇区6：V6-V1边界区域（330°~360°/0°）
        } else {
            // 第三象限：α<0, β<0
            // 边界线对应210°（即180°+30°）
            if (one_by_sqrt3 * beta > alpha)
                Sextant = 4; // 扇区4：V4-V5边界区域（150°~210°）
            else
                Sextant = 5; // 扇区5：V5-V6边界区域（210°~270°）
        }
    }

    /* ===== 计算各矢量的作用时间并生成PWM占空比 =====
     * 根据所在扇区，使用相邻两个有效矢量合成目标矢量。
     * 通过伏秒平衡方程计算各矢量的归一化作用时间（以PWM周期Ts=1为基准），
     * 然后转换为三相PWM的占空比。
     *
     * 七段式SVM的PWM序列在一个周期内对称分布：
     *   ... → 零矢量 → Vx → Vy → 零矢量 → Vy → Vx → 零矢量 → ...
     * 这种对称分布可以减少输出谐波，是SVM优于SPWM的关键之一。
     */
    switch (Sextant) {
        // ===== 扇区1：V1-V2区域（0°~60°）=====
        // 目标矢量由V1和V2合成
        // V1 = (1, 0), V2 = (1/2, √3/2)
        // 解方程组得：t1 = α - β/√3, t2 = 2β/√3
        case 1: {
            // 矢量V1和V2的归一化作用时间
            float t1 = alpha - one_by_sqrt3 * beta;    // V1的作用时间
            float t2 = two_by_sqrt3 * beta;            // V2的作用时间

            // PWM占空比计算（七段式对称分布）
            // tA从零矢量中点开始，依次加上t1和t2得到tB和tC的切换点
            *tA = (1.0f - t1 - t2) * 0.5f;  // 零矢量时间的一半作为起始点
            *tB = *tA + t1;                  // A相切换后经过t1时间B相切换
            *tC = *tB + t2;                  // B相切换后经过t2时间C相切换

            break;
        }

        // ===== 扇区2：V2-V3区域（60°~120°）=====
        // 目标矢量由V2和V3合成
        // V2 = (1/2, √3/2), V3 = (-1/2, √3/2)
        case 2: {
            // 矢量V2和V3的归一化作用时间
            float t2 = alpha + one_by_sqrt3 * beta;    // V2的作用时间
            float t3 = -alpha + one_by_sqrt3 * beta;   // V3的作用时间

            // PWM占空比计算（扇区2中B相作为基准相）
            *tB = (1.0f - t2 - t3) * 0.5f;  // B相从零矢量中点开始
            *tA = *tB + t3;                  // 经过t3时间A相切换
            *tC = *tA + t2;                  // 经过t2时间C相切换

            break;
        }

        // ===== 扇区3：V3-V4区域（120°~180°）=====
        // 目标矢量由V3和V4合成
        // V3 = (-1/2, √3/2), V4 = (-1, 0)
        case 3: {
            // 矢量V3和V4的归一化作用时间
            float t3 = two_by_sqrt3 * beta;        // V3的作用时间
            float t4 = -alpha - one_by_sqrt3 * beta; // V4的作用时间

            // PWM占空比计算（扇区3中B相作为基准相）
            *tB = (1.0f - t3 - t4) * 0.5f;
            *tC = *tB + t3;
            *tA = *tC + t4;

            break;
        }

        // ===== 扇区4：V4-V5区域（180°~240°）=====
        // 目标矢量由V4和V5合成
        // V4 = (-1, 0), V5 = (-1/2, -√3/2)
        case 4: {
            // 矢量V4和V5的归一化作用时间
            float t4 = -alpha + one_by_sqrt3 * beta;  // V4的作用时间
            float t5 = -two_by_sqrt3 * beta;          // V5的作用时间

            // PWM占空比计算（扇区4中C相作为基准相）
            *tC = (1.0f - t4 - t5) * 0.5f;
            *tB = *tC + t5;
            *tA = *tB + t4;

            break;
        }

        // ===== 扇区5：V5-V6区域（240°~300°）=====
        // 目标矢量由V5和V6合成
        // V5 = (-1/2, -√3/2), V6 = (1/2, -√3/2)
        case 5: {
            // 矢量V5和V6的归一化作用时间
            float t5 = -alpha - one_by_sqrt3 * beta;  // V5的作用时间
            float t6 = alpha - one_by_sqrt3 * beta;    // V6的作用时间

            // PWM占空比计算（扇区5中C相作为基准相）
            *tC = (1.0f - t5 - t6) * 0.5f;
            *tA = *tC + t5;
            *tB = *tA + t6;

            break;
        }

        // ===== 扇区6：V6-V1区域（300°~360°）=====
        // 目标矢量由V6和V1合成
        // V6 = (1/2, -√3/2), V1 = (1, 0)
        case 6: {
            // 矢量V6和V1的归一化作用时间
            float t6 = -two_by_sqrt3 * beta;           // V6的作用时间
            float t1 = alpha + one_by_sqrt3 * beta;    // V1的作用时间

            // PWM占空比计算（扇区6中A相作为基准相）
            *tA = (1.0f - t6 - t1) * 0.5f;
            *tC = *tA + t1;
            *tB = *tC + t6;

            break;
        }
    }

    /* ===== 越界检查 =====
     * 验证计算出的PWM占空比是否在合法范围[0, 1]内。
     * 如果超出范围，说明输入矢量幅值超过了SVM的线性调制区限制（√3/2），
     * 此时输出波形将失真，返回错误码-1通知调用者。
     * 调用者应对输入进行限幅处理，确保α-β矢量幅值不超过√3/2。
     */
    int retval = 0;
    if (
        *tA < 0.0f
        || *tA > 1.0f
        || *tB < 0.0f
        || *tB > 1.0f
        || *tC < 0.0f
        || *tC > 1.0f
    ) retval = -1;
    return retval;
}

