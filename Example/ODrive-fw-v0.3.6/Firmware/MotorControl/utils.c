/**
 * @brief 角度归一化函数：将角度约束到[-π, π)区间
 *
 * @details
 * 在电机FOC控制中，电角度会随时间不断累加。当角度超过π或小于-π时，
 * 需要将其归一化到[-π, π)区间，以保持角度值的连续性和有界性。
 *
 * 实现方式：
 * - 当角度≥π时，不断减去2π直到小于π
 * - 当角度<-π时，不断加上2π直到大于等于-π
 *
 * 注意：该方法对于角度偏离[-π, π)较近时效率较高。
 * 如果角度值非常大（例如经过长时间累加），可能需要多次循环，
 * 此时建议使用 fmodf() 函数进行归一化。
 *
 * @param[in] theta 输入角度（弧度制），可以是任意值
 * @return 归一化后的角度，范围为 [-π, π)
 * @warning 对于非常大的角度值，循环次数较多，可能影响实时性能
 */
// 警告：注意不要传入过大的角度值！
float wrap_pm_pi(float theta) {
    // 角度上界归一化：如果角度大于等于π，减去2π
    while (theta >= M_PI) theta -= (2.0f * M_PI);
    // 角度下界归一化：如果角度小于-π，加上2π
    while (theta < -M_PI) theta += (2.0f * M_PI);
    return theta;
}

