/* ========================================================================== */

/**
 * @brief 将截止时间（deadline）转换为超时时间（timeout）
 *
 * @details
 * 在RTOS中，有时需要等待某个事件直到某个截止时间（deadline），
 * 但RTOS的等待函数通常接受超时时间（timeout）作为参数。
 * 本函数用于在两者之间进行转换。
 *
 * 截止时间（deadline）：一个绝对时间点（系统启动后的毫秒数）
 * 超时时间（timeout）：从当前时刻到截止时间的剩余毫秒数
 *
 * 溢出处理：
 * uint32_t类型的系统时钟在运行约49.7天后会溢出回绕。
 * 利用补码运算的性质，deadline - now 的差值即使在溢出情况下也是正确的，
 * 前提是超时时间不超过2³¹毫秒（约24.8天）。
 *
 * 通过检查差值的符号位（第31位）来判断截止时间是否已过：
 * - 如果符号位为1，说明差值为负（溢出情况下表现为很大的正数），截止已过，返回0
 * - 否则返回差值作为超时时间
 *
 * @param[in] deadline_ms 截止时间（绝对时间戳，单位：毫秒）
 * @return 超时时间（相对当前剩余的毫秒数）；如果截止时间已过则返回0
 *
 * @note 特殊情况：如果截止时间在很久以前（超过2³¹毫秒），
 *       差值的符号位可能因多次溢出而翻转，此时也会返回0，这是可接受的行为。
 */
// @brief: 返回距离截止时间还剩多少时间。
// 如果截止时间已经过去，返回值为0（除非截止时间在非常久远的过去）
uint32_t deadline_to_timeout(uint32_t deadline_ms) {
    // 获取当前系统时间（毫秒）
    // xTaskGetTickCount() 返回RTOS内核的系统滴答数
    // 通过 (1000 * tick) / frequency 转换为毫秒
    uint32_t now_ms = (uint32_t)((1000ull * (uint64_t)xTaskGetTickCount()) / configTICK_RATE_HZ);

    // 计算截止时间与当前时间的差值
    // 利用无符号整数减法的溢出特性，即使系统时钟溢出也能正确计算
    uint32_t timeout_ms = deadline_ms - now_ms;

    // 检查符号位（第31位）：
    // - 如果为1，说明 deadline < now（截止时间已过），返回0
    // - 如果为0，说明 deadline >= now，返回剩余的超时时间
    return (timeout_ms & 0x80000000) ? 0 : timeout_ms;
}

/**
 * @brief 将超时时间转换为截止时间
 *
 * @details
 * 与 deadline_to_timeout() 相反的操作。
 * 给定一个超时时长（从现在开始等待多久），计算出对应的绝对截止时间点。
 *
 * 使用场景：
 * 当你需要设置一个定时事件，例如"在100ms后执行某操作"，
 * 可以先调用此函数计算出截止时间，然后在循环中不断调用
 * deadline_to_timeout() 检查是否超时。
 *
 * @param[in] timeout_ms 超时时长（从当前时刻开始的毫秒数）
 * @return 截止时间（绝对时间戳，单位：毫秒）
 *
 * @note 由于使用无符号加法，即使 now_ms + timeout_ms 发生溢出，
 *       后续使用 deadline_to_timeout() 也能正确处理溢出情况。
 */
// @brief: 根据超时时长计算出对应的截止时间
uint32_t timeout_to_deadline(uint32_t timeout_ms) {
    // 获取当前系统时间（毫秒）
    uint32_t now_ms = (uint32_t)((1000ull * (uint64_t)xTaskGetTickCount()) / configTICK_RATE_HZ);
    // 截止时间 = 当前时间 + 超时时长
    return now_ms + timeout_ms;
}

