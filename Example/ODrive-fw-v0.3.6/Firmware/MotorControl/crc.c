/**
 * @file crc.c
 * @brief CRC16-CCITT校验实现文件
 *
 * 本文件实现了基于查表法的CRC16-CCITT校验算法。
 *
 * 【查表法原理】
 * 传统的CRC计算采用逐位(bit-by-bit)异或和移位操作，计算效率较低。
 * 查表法预先计算好所有可能的8位字节(0-255)对应的CRC值，存储在一个
 * 256元素的查找表中。计算时，每次处理一个字节，通过查表直接获取该字节
 * 对应的CRC贡献值，大大加快了计算速度(比逐位计算快约8倍)。
 *
 * 【CRC16-CCITT标准】
 * - 生成多项式: G(x) = x^16 + x^12 + x^5 + 1
 * - 多项式二进制: 1 0001 0000 0010 0001 (0x1021)
 * - 初始值: 0x0000
 * - 广泛应用于: Modbus、Kermit、X.25等通信协议
 *
 * 【应用场景】
 * - 通信数据包完整性校验: 发送方计算CRC附加到数据帧末尾，接收方
 *   重新计算并与接收到的CRC比较，若不匹配则说明数据在传输过程中
 *   发生了错误或损坏。
 * - Flash存储器数据校验: 验证从Flash读取的数据是否完整正确。
 */

