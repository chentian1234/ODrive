/**
 * @brief 微秒级精确延时（忙等待实现）
 *
 * @details
 * 使用忙等待（busy-wait / 轮询）方式实现微秒级精确延时。
 * 延时期间CPU持续运行空转循环，不会让出CPU或进入低功耗模式。
 *
 * 实现原理：
 * 1. 记录当前微秒时间戳作为起始时间
 * 2. 循环检查当前时间与起始时间的差值是否达到目标延时
 * 3. 每次循环插入NOP指令，防止编译器优化掉循环
 *
 * @param[in] us 需要延时的微秒数
 *
 * @warning 忙等待会持续占用CPU资源，在延时期间无法执行其他任务。
 *          仅适用于短时间延时（通常<100微秒）。
 *          长时间延时建议使用：
 *          - RTOS的任务延时函数（如 vTaskDelay()）
 *          - 定时器中断回调
 *          - DMA+定时器硬件方式
 */
// @brief: 忙等待延时指定的微秒数（us）
void delay_us(uint32_t us) {
    uint32_t start = micros();  // 记录起始时间戳
    // 循环等待直到经过的时间达到目标值
    while (micros() - start < (uint32_t) us) {
        __ASM("nop");  // 插入空操作指令，防止编译器优化并减少功耗
    }
}
