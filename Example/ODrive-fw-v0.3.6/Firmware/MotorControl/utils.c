/* ========================================================================== */

/**
 * @brief 快速atan2函数：使用多项式近似的二维反正切计算
 *
 * @details
 * atan2(y, x) 计算点(x, y)与原点连线相对于x轴正方向的角度，
 * 是电机FOC控制中估算转子角度的重要函数。
 *
 * 标准库的atan2()函数精度高但计算量大（涉及多次除法、开方、级数展开），
 * 在资源受限的嵌入式MCU上可能成为性能瓶颈。本函数使用多项式近似法，
 * 在保持足够精度的同时将计算速度提升3~5倍。
 *
 * ======================== 算法原理详解 ========================
 *
 * 【算法来源】
 * 基于 https://math.stackexchange.com/a/1105038/81278 中的近似公式
 *
 * 【步骤1：利用对称性归约到第一卦限】
 * atan2具有以下对称性质：
 * - atan2(-y, x) = -atan2(y, x)           （x轴对称）
 * - atan2(y, -x) = π - atan2(y, x)        （y轴对称）
 * - atan2(-y, -x) = atan2(y, x) - π       （原点对称）
 * - 当|y| > |x|时：atan2(y, x) = π/2 - atan2(x, y)  （对角线对称）
 *
 * 利用这些对称性，可以将任意象限的计算归约到区域：0 ≤ |y| ≤ |x|, x > 0
 * 在该区域内，atan2的返回值范围为[0, π/4]
 *
 * 【步骤2：变量替换】
 * 令 a = min(|x|, |y|) / max(|x|, |y|)
 * 在归约后的区域内，有 a = |y| / |x|，且 a ∈ [0, 1]
 *
 * 此时 arctan(a) 就是我们需要近似的函数，其中 a ∈ [0, 1]
 *
 * 【步骤3：多项式近似】
 * 在区间[0, 1]上，使用三次多项式逼近arctan(a)：
 *
 *   arctan(a) ≈ a + s·(C1 + s·(C2 + s·C3))·a
 *
 * 其中 s = a²，系数为：
 *   C3 = -0.0464964749    （三次项系数）
 *   C2 =  0.15931422      （二次项系数）
 *   C1 = -0.327622764     （一次项系数）
 *
 * 完整展开式：
 *   r = a + a³·(-0.327622764 + a²·(0.15931422 + a²·(-0.0464964749)))
 *     = a + s·a·(C1 + s·(C2 + s·C3))
 *
 * 这些系数是通过Minimax近似（最小化最大误差）方法优化得到的，
 * 使得在整个[0, 1]区间上的最大绝对误差最小化。
 *
 * 【步骤4：象限修正】
 * 根据原始(x, y)的符号和大小关系，对近似结果进行对称变换：
 * - 如果|y| > |x|：r = π/2 - r    （利用对角线对称性）
 * - 如果x < 0：   r = π - r       （利用y轴对称性）
 * - 如果y < 0：   r = -r          （利用x轴对称性）
 *
 * 【精度分析】
 * - 最大绝对误差：< 0.0015 弧度（约0.086度）
 * - 计算速度：比标准atan2快3~5倍（取决于平台和编译器）
 * - 适用于：电机角度估算、坐标变换等对实时性要求高、精度要求中等的场景
 *
 * @param[in] y y坐标值（分子，对应三角函数中的对边）
 * @param[in] x x坐标值（分母，对应三角函数中的邻边）
 * @return 近似角度值，范围为 (-π, π]
 */
// 算法来源: https://math.stackexchange.com/a/1105038/81278
float fast_atan2(float y, float x) {
    // 【步骤1】计算|x|和|y|，用于归约到第一卦限
    float abs_y = fabsf(y);    // |y|
    float abs_x = fabsf(x);    // |x|

    // 【步骤2】计算 a = min(|x|, |y|) / max(|x|, |y|)
    // a 的值域为 [0, 1]，在归约后的区域内 a = |y|/|x|
    float a = MACRO_MIN(abs_x, abs_y) / MACRO_MAX(abs_x, abs_y);

    // 【步骤3】计算 s = a²
    float s = a * a;

    // 【步骤4】三次多项式近似 arctan(a)
    // r = a + s·a·(C1 + s·(C2 + s·C3))
    // 使用霍纳法则（Horner's method）嵌套计算，减少乘法次数：
    // r = ((C3·s + C2)·s + C1)·s·a + a
    float r = ((-0.0464964749f * s + 0.15931422f) * s - 0.327622764f) * s * a + a;

    // 【步骤5】根据|y|与|x|的大小关系进行对角线对称修正
    // 如果|y| > |x|，说明角度在45°~90°（或对应象限）
    // 利用恒等式：arctan(y/x) = π/2 - arctan(x/y)
    if (abs_y > abs_x)
        r = 1.57079637f - r;  // π/2 ≈ 1.57079637

    // 【步骤6】根据x的符号进行y轴对称修正
    // 如果x < 0，说明角度在第二或第三象限
    // 利用恒等式：atan2(y, -x) = π - atan2(y, x)
    if (x < 0.0f)
        r = 3.14159274f - r;  // π ≈ 3.14159274

    // 【步骤7】根据y的符号进行x轴对称修正
    // 如果y < 0，说明角度在第三或第四象限（角度应为负值）
    // 利用恒等式：atan2(-y, x) = -atan2(y, x)
    if (y < 0.0f)
        r = -r;

    return r;
}

